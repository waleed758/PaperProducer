function translate(text, language) {
  if (language !== 'ur' || typeof text !== 'string') return text
  const trimmed = text.trim()
  if (!trimmed) return text
  let result = urdu[trimmed]
  if (result === undefined) {
    const emptyTitle = trimmed.match(/^No (.+) yet$/)
    const emptyLoaded = trimmed.match(/^No (.+) loaded$/)
    const name = emptyTitle?.[1] ?? emptyLoaded?.[1]
    if (name) {
      const key = name[0].toUpperCase() + name.slice(1)
      const translatedName = urdu[key] ?? name
      result = emptyTitle
        ? `ابھی کوئی ${translatedName} موجود نہیں۔`
        : `${translatedName} کا ریکارڈ دستیاب نہیں۔`
    }
  }
  return result === undefined ? text : text.replace(trimmed, result)
}

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    try {
      return localStorage.getItem(LANGUAGE_KEY) === 'ur' ? 'ur' : 'en'
    } catch {
      return 'en'
    }
  })

  useEffect(() => {
    const root = document.documentElement
    root.lang = language
    root.dir = language === 'ur' ? 'rtl' : 'ltr'
    document.title = translate('Paper Producer', language)
    const description = document.querySelector('meta[name="description"]')
    if (description) description.content = translate('Paper Producer — just click to make it real.', language)
    try {
      localStorage.setItem(LANGUAGE_KEY, language)
    } catch {
      // Language choice still works for this session when storage is unavailable.
    }
  }, [language])

  const value = useMemo(() => ({
    language,
    direction: language === 'ur' ? 'rtl' : 'ltr',
    t: (text) => translate(text, language),
    toggleLanguage: () => setLanguage((current) => current === 'en' ? 'ur' : 'en'),
  }), [language])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  const value = useContext(LanguageContext)
  if (!value) throw new Error('useLanguage must be used within LanguageProvider')
  return value
}
